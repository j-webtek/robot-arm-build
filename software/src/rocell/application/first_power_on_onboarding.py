def _next_safe_action(report: FirstPowerOnReport) -> str:
    blocked = report.first_blocked_stage
    if blocked is not None:
        return (
            f"Correct the injected or observed condition at {blocked.value}; start a new "
            "explicit attempt or resume only after revalidating the checkpoint."
        )
    next_stage = report.next_stage
    if next_stage is not None:
        return f"Explicitly resume the rehearsal at {next_stage.value}; no hardware action is implied."
    return (
        "When the camera arrives, begin physical CAMERA_RECEIPT with RoArm actuator "
        "power isolated; do not power the robot from this rehearsal result."
    )


def _fault_cleanup_diagnostics(report: FirstPowerOnReport) -> tuple[str, bool]:
    """Derive cleanup status from the boundary that was actually exercised.

    Most failures happen before even a simulated resource is opened. Feedback
    and noncontact route faults deliberately open an in-memory transport or a
    virtual arm plant, so those results must come from explicit stage checks
    rather than from an unconditional success value.
    """

    blocked = report.first_blocked_stage
    if blocked is None or not report.records:
        return ("NOT_APPLICABLE_NO_RESOURCE_OPENED", True)
    checks = {check.check_id: check.passed for check in report.records[-1].checks}
    if blocked is OnboardingStage.FEEDBACK_ONLY_CONNECTION:
        satisfied = checks.get("transport_cleanup_closed", False)
        return (
            "SYNTHETIC_SERIAL_TRANSPORT_CLOSED"
            if satisfied
            else "SYNTHETIC_SERIAL_TRANSPORT_CLEANUP_FAILED",
            satisfied,
        )
    if blocked is OnboardingStage.NONCONTACT_ACCEPTANCE:
        satisfied = checks.get("fault_cleanup_closed", False)
        return (
            "VIRTUAL_ARM_CLOSED_AFTER_FAIL_STOP"
            if satisfied
            else "VIRTUAL_ARM_CLEANUP_FAILED",
            satisfied,
        )
    return ("NOT_APPLICABLE_NO_RESOURCE_OPENED", True)


class DeterministicOnboardingProvider:
    """Exercise real software boundaries with only synthetic/replay inputs."""

    provider_id = "deterministic_first_power_on_provider_v1"
    simulation_only = True
    hardware_accessed = False

    _IDENTITY_CHECKS = {
        "profile_binding",
        "unique_inventory",
        "persistent_selector",
        "identity_policy",
        "profile_product",
        "reconnect_identity",
    }
    _MODE_CHECKS = {
        "native_mode_advertised",
        "native_mode_selected",
        "usb3_negotiated",
        "manual_exposure",
        "manual_white_balance",
        "settings_stability",
    }

    @classmethod
    def _uvc_check_contract_is_exact(cls, assessment: Any) -> bool:
        """Prevent a renamed or omitted upstream gate from passing by filtering."""

        check_ids = tuple(check.check_id for check in assessment.checks)
        expected = cls._IDENTITY_CHECKS | cls._MODE_CHECKS
        return len(check_ids) == len(expected) and set(check_ids) == expected

    def __init__(self, workspace: Path, scenario: OnboardingScenario) -> None:
        self.workspace = workspace.resolve()
        self.scenario = scenario
        self._bootstrap: Any | None = None
        self._camera_profile: Any | None = None
        self._uvc_results: dict[str, tuple[Any, Any]] = {}
        self._vision_reports: dict[tuple[int, str], Any] = {}

    def probe(self, stage: OnboardingStage) -> OnboardingProbeResult:
        method = getattr(self, f"_probe_{stage.value}", None)
        if not callable(method):  # pragma: no cover - guarded by enum/test completeness
            raise FirstPowerOnError(f"provider has no probe for {stage.value}")
        result = method()
        if not isinstance(result, OnboardingProbeResult):
            raise FirstPowerOnError(f"provider returned an invalid result for {stage.value}")
        return result

    @staticmethod
    def _checks(*items: tuple[str, bool, str]) -> tuple[OnboardingCheck, ...]:
        return tuple(OnboardingCheck(*item) for item in items)

    def _profile(self) -> Any:
        if self._camera_profile is None:
            from rocell.vision.camera_profile import load_camera_profile

            self._camera_profile = load_camera_profile(
                _contained_file(self.workspace, _PROFILE_PATH)
            )
        return self._camera_profile

    def _load_uvc(self, *, mode_stage: bool) -> tuple[Any, Any]:
        # Mode/settings faults belong only to Stage 5. Stage 4 must retain the
        # exact nominal identity evidence so a later injected fault cannot
        # contaminate a successful prefix record.
        apply_mode_fault = mode_stage and self.scenario in {
            OnboardingScenario.CAMERA_USB2,
            OnboardingScenario.CAMERA_SETTINGS_DRIFT,
        }
        cache_key = "mode_fault" if apply_mode_fault else "base"
        cached = self._uvc_results.get(cache_key)
        if cached is not None:
            return cached

        from rocell.vision.uvc_inventory import (
            DeterministicFakeUvcInventoryProvider,
            UvcDevice,
            UvcDeviceIdentity,
            UvcMode,
            assess_uvc_inventory,
            collect_uvc_inventory,
            parse_uvc_inventory_json,
        )

        path = _contained_file(self.workspace, _UVC_FIXTURE_PATH)
        inventory = parse_uvc_inventory_json(path.read_bytes())
        snapshots = list(inventory.reopen_snapshots)
        selector_value = inventory.selector_value

        if self.scenario is OnboardingScenario.CAMERA_MISSING:
            # A snapshot is structurally required to retain at least one host
            # device.  Model an absent selected camera with a persistent
            # selector that resolves none, rather than weakening that bound.
            selector_value = "synthetic://camera/arducam-b0477/not-present"
        elif self.scenario is OnboardingScenario.CAMERA_WRONG_IDENTITY:
            changed = []
            for snapshot in snapshots:
                device = snapshot.devices[0]
                identity = UvcDeviceIdentity(
                    vid=device.identity.vid,
                    pid=device.identity.pid,
                    serial_number=device.identity.serial_number,
                    persistent_path=device.identity.persistent_path,
                    manufacturer="Generic Vendor",
                    product="Generic USB Camera",
                )
                changed.append(
                    replace(snapshot, devices=(UvcDevice(identity, device.modes),))
                )
            snapshots = changed
        elif apply_mode_fault and self.scenario is OnboardingScenario.CAMERA_USB2:
            fallback = UvcMode(1280, 720, 10.0, "YUY2", "USB_2_0")
            snapshots = [
                replace(
                    snapshot,
                    negotiated_bus="USB_2_0",
                    selected_mode=fallback,
                )
                for snapshot in snapshots
            ]
        elif (
            apply_mode_fault
            and self.scenario is OnboardingScenario.CAMERA_SETTINGS_DRIFT
        ):
            second = snapshots[1]
            controls = tuple(
                replace(control, value=control.value + 1000.0)
                if control.control_id == "exposure"
                else control
                for control in second.controls
            )
            snapshots[1] = replace(second, controls=controls)

        inventory = replace(
            inventory,
            selector_value=selector_value,
            reopen_snapshots=tuple(snapshots),
        )
        inventory = collect_uvc_inventory(DeterministicFakeUvcInventoryProvider(inventory))
        assessment = assess_uvc_inventory(self._profile(), inventory)
        result = (inventory, assessment)
        self._uvc_results[cache_key] = result
        return result

