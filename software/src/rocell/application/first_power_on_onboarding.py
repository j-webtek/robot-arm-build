    def _probe_feedback_only_connection(self) -> OnboardingProbeResult:
        from rocell.arm import (
            DeterministicFeedbackSession,
            ProtocolEmulatorFault,
            ProtocolEmulatorSessionError,
            ProtocolEmulatorSessionFailure,
            ProtocolEmulatorStep,
            parse_feedback_1051,
        )

        fault_map = {
            OnboardingScenario.ARM_TIMEOUT: ProtocolEmulatorFault.TIMEOUT,
            OnboardingScenario.ARM_MALFORMED_FEEDBACK: ProtocolEmulatorFault.MALFORMED_JSON,
            OnboardingScenario.ARM_DISCONNECT: ProtocolEmulatorFault.DISCONNECT,
            OnboardingScenario.ARM_RESET_BANNER: ProtocolEmulatorFault.RESET_BANNER,
        }
        fault = fault_map.get(self.scenario)
        steps: tuple[ProtocolEmulatorStep, ...]
        if fault is not None:
            steps = (ProtocolEmulatorStep(fault),)
        elif self.scenario is OnboardingScenario.ARM_INCOMPLETE_FEEDBACK:
            steps = (ProtocolEmulatorStep(feedback_fields={}),)
        else:
            base = {
                "x": 344.9,
                "y": 4.7,
                "z": 206.9,
                "tit": 0.05,
                "b": 0.01,
                "s": 0.0,
                "e": 1.61,
                "t": 0.02,
                "r": -0.01,
                "g": 3.13,
                "tB": -44,
                "tS": 0,
                "tE": 128,
                "tT": 48,
                "tR": 32,
                "tG": -20,
                "torswitchB": 1,
                "torswitchS": 1,
                "torswitchE": 1,
                "torswitchT": 1,
                "torswitchR": 1,
                "torswitchG": 0,
                "v": 1210,
            }
            steps = (
                ProtocolEmulatorStep(feedback_fields=base),
                ProtocolEmulatorStep(feedback_fields=base),
            )

        # The session owns a DeterministicProtocolController internally and is
        # intentionally not an ArmTransport.  It accepts no FeedbackPermit, so
        # this zero-authority rehearsal cannot mint a capability transferable
        # to a live SerialTransport.
        transport = DeterministicFeedbackSession(steps, max_line_bytes=4096)
        replies: list[Any] = []
        transport_failure: ProtocolEmulatorSessionFailure | None = None
        stale_input_line: bytes | None = None
        requested_exchange_count = (
            1
            if fault is not None
            or self.scenario is OnboardingScenario.ARM_INCOMPLETE_FEEDBACK
            else 2
        )
        for exchange_index in range(requested_exchange_count):
            try:
                if (
                    self.scenario is OnboardingScenario.ARM_STALE_FEEDBACK
                    and exchange_index == 1
                ):
                    # T=1051 has no echoed host transaction identifier.  A
                    # syntactically valid line that predates this request can
                    # never be correlated safely, so the buffer check must
                    # reject it before a second T=105 is written.
                    stale_input_line = steps[0].response_line
                    transport.inject_preexisting_input(stale_input_line)
                transport.connect()
                replies.append(transport.request_feedback())
            except (ProtocolEmulatorSessionError, OSError, ValueError) as exc:
                transport_failure = (
                    exc.failure
                    if isinstance(exc, ProtocolEmulatorSessionError)
                    else ProtocolEmulatorSessionFailure.IO_FAILURE
                )
                break
            finally:
                if transport.is_open:
                    transport.close()

        typed_replies = tuple(parse_feedback_1051(reply) for reply in replies)
        required_joint_names = {
            "base",
            "shoulder",
            "elbow",
            "wrist_pitch",
            "wrist_roll",
            "gripper",
        }
        complete = len(typed_replies) == requested_exchange_count and all(
            all(
                value is not None
                for value in (
                    reply.x_mm,
                    reply.y_mm,
                    reply.z_mm,
                    reply.endpoint_pitch_rad,
                    reply.base_rad,
                    reply.shoulder_rad,
                    reply.elbow_rad,
                    reply.wrist_pitch_rad,
                    reply.wrist_roll_rad,
                    reply.gripper_rad,
                    reply.voltage_raw_0p01_v,
                )
            )
            and set(reply.loads_raw) == required_joint_names
            and set(reply.torque_switches) == required_joint_names
            for reply in typed_replies
        )
        receive_buffer_quiescent = (
            transport_failure
            is not ProtocolEmulatorSessionFailure.STALE_BUFFERED_INPUT
        )
        exact_requests = all(message == {"T": 105} for message in transport.sent_messages)
        expected_count = (
            requested_exchange_count if transport_failure is None else 1
        )
        bounded_count = len(transport.writes) == expected_count
        transport_cleanup_closed = (
            not transport.is_open
            and transport.close_count == transport.open_count
        )
        passed = (
            transport_failure is None
            and complete
            and exact_requests
            and bounded_count
            and transport_cleanup_closed
        )
        observed_failure_details = {
            ProtocolEmulatorSessionFailure.TIMEOUT: "ARM_FEEDBACK_TIMEOUT_BLOCKED",
            ProtocolEmulatorSessionFailure.MALFORMED_JSON: "ARM_FEEDBACK_MALFORMED_BLOCKED",
            ProtocolEmulatorSessionFailure.DISCONNECT: "ARM_FEEDBACK_DISCONNECT_BLOCKED",
            ProtocolEmulatorSessionFailure.RESET_BANNER: "ARM_RESET_BANNER_BLOCKED",
            ProtocolEmulatorSessionFailure.STALE_BUFFERED_INPUT: "ARM_STALE_BUFFERED_FEEDBACK_BLOCKED",
        }
        failure_classified = (
            transport_failure is None
            or transport_failure in observed_failure_details
        )
        if passed:
            detail_code = "FEEDBACK_ONLY_CONNECTION_REHEARSED"
        elif transport_failure is not None:
            detail_code = observed_failure_details.get(
                transport_failure,
                "ARM_FEEDBACK_UNCLASSIFIED_BLOCKED",
            )
        elif not complete:
            detail_code = "ARM_FEEDBACK_INCOMPLETE_BLOCKED"
        else:  # pragma: no cover - all current verdict terms are enumerated above
            detail_code = "FEEDBACK_ONLY_CONNECTION_BLOCKED"
        checks = self._checks(
            ("serial_exchange", transport_failure is None, "injected serial open/query/close completed without reset or transport fault"),
            ("feedback_complete", complete, "typed feedback contains endpoint pose, six joints, six loads, six torque switches, and voltage"),
            (
                "receive_buffer_quiescent",
                receive_buffer_quiescent,
                "no response bytes predate the corresponding synthetic T=105 request",
            ),
            ("only_t105", exact_requests, "every emitted synthetic line is exactly the T=105 feedback request"),
            ("no_blind_retry", bounded_count, "a failed transaction is quarantined and never retried automatically"),
            (
                "failure_classification_known",
                failure_classified,
                "any emulated wire failure is classified from observed behavior rather than from the requested scenario name",
            ),
            (
                "transport_cleanup_closed",
                transport_cleanup_closed,
                "every opened synthetic serial connection is closed after success or quarantine",
            ),
            (
                "fresh_stage12_envelope_required",
                True,
                "physical feedback acquisition requires a new Stage-12 envelope after Stage 11 has ended de-energized",
            ),
            (
                "permit_precedes_serial_open",
                True,
                "the physical one-use permit must be consumed before port open; this emulator mints no live permit and opens no OS port",
            ),
            (
                "serial_open_possible_motion_effect",
                True,
                "serial open is classified as a possible ESP32 reset or motion effect even though the only permitted request is non-motion T=105",
            ),
            (
                "final_deenergized_state_required",
                True,
                "the physical Stage-12 transaction must close and finish with independently observed actuator power off",
            ),
        )
        evidence = {
            "provider": "deterministic_protocol_controller",
            "physical_sequence_contract": {
                "prior_stage_final_state_required": "DEENERGIZED",
                "fresh_stage12_energization_envelope_required": True,
                "one_use_permit_consumed_before_serial_open": True,
                "serial_open_classification": "POSSIBLE_RESET_OR_MOTION_EFFECT",
                "t105_classification": "FEEDBACK_REQUEST_NOT_MOTION_COMMAND",
                "final_actuator_state_required": "DEENERGIZED",
                "standing_power_authority_created": False,
            },
            "sent_line_sha256": [hashlib.sha256(line).hexdigest() for line in transport.writes],
            "scripted_reply_sha256": [step.feedback_sha256 for step in steps],
            "received_reply_sha256": [
                hashlib.sha256(line).hexdigest()
                for line in transport.received_lines
            ],
            "stale_preexisting_input_sha256": (
                hashlib.sha256(stale_input_line).hexdigest()
                if stale_input_line is not None
                else None
            ),
            "observed_transport_failure": (
                transport_failure.value
                if transport_failure is not None
                else None
            ),
            "requested_exchange_count": requested_exchange_count,
            "completed_exchange_count": len(replies),
            "open_count": transport.open_count,
            "close_count": transport.close_count,
            "motion_commands": 0,
            "live_feedback_permits_minted": 0,
        }
        return OnboardingProbeResult(
            passed,
            detail_code,
            "Exact framing, lazy-open, pre-request receive-buffer freshness, no-retry, typed parsing, bounded exchange accounting, and quarantine boundaries run in a hardware-incapable emulator without minting a live permit.",
            checks,
            (("protocol_transcript", _canonical_hash(evidence)),),
            emulated_feedback_queries=len(transport.writes),
        )

