"""Deterministic rehearsal of the first physical power-on workflow.

The individual RoCell subsystems already expose strict, hardware-free seams for
the frozen workspace, the selected B0477 camera, and the RoArm serial protocol.
This module joins those seams into the order an operator will eventually use.

The distinction between *rehearsing* a gate and *satisfying* a physical gate is
deliberate and permanent:

* this runner constructs only its built-in
  :class:`DeterministicOnboardingProvider`;
* every record says ``SYNTHETIC_REHEARSAL``;
* no OS device is enumerated and no real port is opened;
* the serial exercise uses a hardware-incapable emulator session that cannot
  mint or consume a live ``FeedbackPermit``;
* no T=104 motion method is called; and
* even a completely successful run ends with physical commissioning, robot
  power, motion, and contact authority set to false.

RoArm actuator power is itself treated as a motion event.  The documented
factory behavior can move the arm toward its middle position at power-on, so a
future operator must clear and contain the startup swept volume *before*
energizing.  "Feedback-only" therefore means no host-issued motion; it does not
mean that cold power-up is physically motionless.
"""

