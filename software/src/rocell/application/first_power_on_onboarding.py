def _canonical_hash(value: object) -> str:
    try:
        payload = json.dumps(
            value,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=True,
            allow_nan=False,
        ).encode("utf-8")
    except (TypeError, ValueError) as exc:
        raise FirstPowerOnError("onboarding value is not canonical JSON") from exc
    return hashlib.sha256(payload).hexdigest()


def _phase1_calibration_dependency_ids(graph: Any) -> tuple[str, ...]:
    """Return the namespaced static-calibration dependency set in stable order.

    The complete shared graph has 15 entries.  Each device-specific closure has
    12 entries, but those closure entries are deliberately retained under a
    device namespace instead of being deduplicated.  This calibration-only set
    is distinct from the 39 top-level CommissioningBundle components defined by
    the physical-onboarding stage catalog.
    """

    return (
        *(f"shared:{artifact_id}" for artifact_id in graph.ordered_requirements),
        *(
            f"keyboard:{artifact_id}"
            for artifact_id in graph.device_closure("keyboard")
        ),
        *(f"phone:{artifact_id}" for artifact_id in graph.device_closure("phone")),
    )


def _file_hash(path: Path) -> str:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError as exc:
        raise FirstPowerOnError(f"cannot read onboarding source {path}: {exc}") from exc


def _reject_symlink_components(root: Path, candidate: Path, label: str) -> None:
    """Reject a lexical path that crosses a link before ``resolve`` hides it."""

    lexical_candidate = Path(os.path.abspath(candidate))
    for component in (lexical_candidate, *lexical_candidate.parents):
        if component.is_symlink():
            raise FirstPowerOnError(f"{label} path cannot contain a symlink")
        if component == root:
            break


def _contained_file(workspace: Path, relative: Path) -> Path:
    root = workspace.resolve()
    candidate = root / relative
    _reject_symlink_components(root, candidate, "onboarding source")
    selected = candidate.resolve()
    try:
        selected.relative_to(root)
    except ValueError as exc:
        raise FirstPowerOnError(f"onboarding source escapes workspace: {relative}") from exc
    if not selected.is_file() or selected.is_symlink():
        raise FirstPowerOnError(f"onboarding source is not a regular file: {relative}")
    return selected


def _source_paths(workspace: Path) -> tuple[Path, ...]:
    """Enumerate the complete bounded implementation/input dependency set."""

    root = workspace.resolve()
    relative_paths = set(_SOURCE_PATHS)
    for relative_root, suffixes in _SOURCE_ROOT_SUFFIXES:
        directory = root / relative_root
        _reject_symlink_components(root, directory, "onboarding source root")
        if not directory.is_dir():
            raise FirstPowerOnError(
                f"onboarding source root is missing: {relative_root.as_posix()}"
            )
        for candidate in directory.rglob("*"):
            if candidate.is_symlink():
                raise FirstPowerOnError(
                    "onboarding source path cannot contain a symlink"
                )
            if candidate.is_file() and candidate.suffix.lower() in suffixes:
                relative_paths.add(candidate.relative_to(root))
    return tuple(sorted(relative_paths, key=lambda item: item.as_posix()))


def _source_bindings(workspace: Path) -> tuple[tuple[str, str], ...]:
    bindings = [
        (
            relative.as_posix(),
            _file_hash(_contained_file(workspace, relative)),
        )
        for relative in _source_paths(workspace)
    ]
    try:
        from PIL import __version__ as pillow_version
        from PIL import features as pillow_features

        runtime = {
            "python_implementation": platform.python_implementation(),
            "python_version": platform.python_version(),
            "operating_system": platform.system(),
            "machine": platform.machine(),
            "pillow_version": pillow_version,
            "jpeg_codec_version": pillow_features.version_codec("jpg"),
        }
    except Exception as exc:
        raise FirstPowerOnError(
            f"cannot bind deterministic runtime dependencies: {exc}"
        ) from exc
    bindings.append(("@runtime/deterministic_stack", _canonical_hash(runtime)))
    return tuple(sorted(bindings))


def _workflow_definition_hash() -> str:
    return _canonical_hash([definition.to_dict() for definition in _STAGE_DEFINITIONS])


def _run_binding_hash(source_bindings: Sequence[tuple[str, str]]) -> str:
    return _canonical_hash(
        {
            "workflow_schema": FIRST_POWER_ON_SCHEMA,
            "workflow_definition_sha256": _workflow_definition_hash(),
            "source_bindings": [
                {"path": path, "sha256": digest} for path, digest in source_bindings
            ],
        }
    )


@dataclass(frozen=True, slots=True)
class OnboardingCheck:
    check_id: str
    passed: bool
    detail: str

    def __post_init__(self) -> None:
        if not isinstance(self.check_id, str) or _IDENTIFIER.fullmatch(self.check_id) is None:
            raise FirstPowerOnError("onboarding check_id is invalid")
        if not isinstance(self.passed, bool):
            raise FirstPowerOnError("onboarding check passed must be boolean")
        if not isinstance(self.detail, str) or not self.detail or len(self.detail) > 2048:
            raise FirstPowerOnError("onboarding check detail is invalid")

    def to_dict(self) -> dict[str, object]:
        return {"check_id": self.check_id, "passed": self.passed, "detail": self.detail}


@dataclass(frozen=True, slots=True)
class OnboardingProbeResult:
    """Provider-owned result before it is joined to the hash chain."""

    passed: bool
    detail_code: str
    summary: str
    checks: tuple[OnboardingCheck, ...]
    evidence_hashes: tuple[tuple[str, str], ...] = ()
    emulated_camera_frames: int = 0
    emulated_feedback_queries: int = 0
    virtual_waypoints_executed: int = 0
    virtual_contact_attempts: int = 0
    virtual_contacts_accepted: int = 0
    virtual_observations: int = 0

    def __post_init__(self) -> None:
        if not isinstance(self.passed, bool):
            raise FirstPowerOnError("probe passed must be boolean")
        if not isinstance(self.detail_code, str) or not self.detail_code:
            raise FirstPowerOnError("probe detail_code is required")
        if not isinstance(self.summary, str) or not self.summary:
            raise FirstPowerOnError("probe summary is required")
        if not isinstance(self.checks, tuple) or not self.checks:
            raise FirstPowerOnError("probe checks must be a non-empty tuple")
        if self.passed != all(check.passed for check in self.checks):
            raise FirstPowerOnError("probe verdict disagrees with its checks")
        names = tuple(name for name, _ in self.evidence_hashes)
        if names != tuple(sorted(names)) or len(names) != len(set(names)):
            raise FirstPowerOnError("probe evidence hashes must be unique and sorted")
        for name, digest in self.evidence_hashes:
            if _IDENTIFIER.fullmatch(name) is None or _DIGEST.fullmatch(digest) is None:
                raise FirstPowerOnError("probe evidence hash is invalid")
        for label, value in (
            ("emulated_camera_frames", self.emulated_camera_frames),
            ("emulated_feedback_queries", self.emulated_feedback_queries),
            ("virtual_waypoints_executed", self.virtual_waypoints_executed),
            ("virtual_contact_attempts", self.virtual_contact_attempts),
            ("virtual_contacts_accepted", self.virtual_contacts_accepted),
            ("virtual_observations", self.virtual_observations),
        ):
            if isinstance(value, bool) or not isinstance(value, int) or value < 0:
                raise FirstPowerOnError(f"{label} must be a nonnegative integer")


